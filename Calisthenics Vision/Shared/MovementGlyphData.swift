//
//  MovementGlyphData.swift
//  Calisthenics Vision
//
//  One drawn pose per movement, as joint angles.
//
//  These are data, not art files: a pose is a hip position, a spine angle and
//  two angles per limb, over fixed bone lengths (`MovementGlyph.Bone`). That
//  means a glyph can never be drawn with a stretched limb, it scales to any
//  size without assets, and it tints with the rest of the UI.
//
//  Angles are absolute degrees: 0 points right (+x), 90 points down (+y), in a
//  100x100 space whose floor is y = 88. The near-side limbs are drawn over the
//  torso and the far side behind it, which is what stops a figure reading as
//  one-armed.
//
//  Movements absent from this table fall back to their category symbol — an
//  honest gap rather than a wrong picture.
//

